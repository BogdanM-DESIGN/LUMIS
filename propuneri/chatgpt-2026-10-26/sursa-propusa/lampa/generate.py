"""Builds every LUMIS part from spec.json.

    python lampa/generate.py            # print files (3MF, already oriented for the bed) + website data
    python lampa/generate.py --stl      # also write STL copies
    python lampa/generate.py --quick    # coarse shades, for a fast check

Outputs
  lampa/print/*.3mf               one file per part, placed and oriented for printing
  data/lamp-spec.js               the same spec for the website's 3D preview
  tests/fixtures/shape-samples.json  radius samples, so a test can prove site and print agree
"""
import argparse
import json
import math
import sys
from pathlib import Path

import numpy as np
import trimesh

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import geom  # noqa: E402

ROOT = HERE.parent


def place_on_bed(m, flip=False):
    m = m.copy()
    if flip:
        m.apply_transform(trimesh.transformations.rotation_matrix(math.pi, [1, 0, 0]))
    m.apply_translation([0, 0, -m.bounds[0][2]])
    return m


def parts(quick=False):
    res = dict(nth=360, nz=120) if quick else {}
    out = {}
    for s in ('wave', 'twist', 'ribbed'):
        out[f'abajur-{s}'] = (geom.shade(s, **res), False)
    for b in ('galet', 'monolit', 'con'):
        out[f'soclu-{b}'] = (geom.base(b), False)           # printed upright: every outward step is at most 45 degrees
        out[f'capac-jos-{b}'] = (geom.bottom_plate(b), False)
    out['difuzor'] = (geom.diffuser(), True)                 # closed end on the plate
    out['inel'] = (geom.ring(), False)
    return out


def samples():
    th = np.linspace(0, 2 * np.pi, 37)
    zn = np.linspace(0, 1, 23)
    ZN, TH = np.meshgrid(zn, th, indexing='ij')
    shades = {k: geom.shade_radius(k, TH, ZN).round(6).tolist() for k in ('wave', 'twist', 'ribbed', 'litho')}
    bases = {k: geom.base_profile(k).round(6).tolist() for k in ('galet', 'monolit', 'con')}
    return {'theta': th.round(9).tolist(), 'zn': zn.round(9).tolist(), 'shades': shades, 'base_profiles': bases}


if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--stl', action='store_true')
    ap.add_argument('--quick', action='store_true')
    a = ap.parse_args()

    (ROOT / 'data' / 'lamp-spec.js').write_text(
        '// Generated by lampa/generate.py from lampa/spec.json. Do not edit by hand.\n'
        f'export const LAMP = {json.dumps(geom.SPEC, ensure_ascii=False, indent=2)};\n', encoding='utf-8')
    fx = ROOT / 'tests' / 'fixtures'
    fx.mkdir(parents=True, exist_ok=True)
    (fx / 'shape-samples.json').write_text(json.dumps(samples()))

    pr = HERE / 'print'
    pr.mkdir(exist_ok=True)
    report = []
    for name, (m, flip) in parts(a.quick).items():
        m = place_on_bed(m, flip)
        assert m.is_watertight, name
        m.export(pr / f'{name}.3mf')
        if a.stl:
            m.export(pr / f'{name}.stl')
        ext = m.extents
        report.append(f'{name:20s} {ext[0]:6.1f} x {ext[1]:6.1f} x {ext[2]:6.1f} mm  {m.volume / 1000:6.1f} cm3  ~{m.volume / 1000 * 1.24:5.0f} g PLA (plin)')
        print(report[-1])
    (pr / 'dimensiuni.txt').write_text('\n'.join(report) + '\n', encoding='utf-8')
